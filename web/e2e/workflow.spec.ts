  await file.setInputFiles('../fixtures/synthetic/conversations.json')
  await page.getByRole('checkbox', { name: /Choose a portable notes format/ }).check()
  await page.getByRole('button', { name: '导入所选' }).click()
  const decision = page.getByText('Keep structured records in Postgres and make approved notes portable as Markdown.', { exact: true })
  await expect(decision).toBeVisible()
  await expect(page.locator('.timeline-item')).toHaveCount(2)

  const sections = Array.from({ length: 101 }, (_, index) => '## 2026-11-20 Synthetic section ' + index + '\n\nGenerated pagination material.').join('\n\n')
  await file.setInputFiles({ name: 'pagination.md', mimeType: 'text/markdown', buffer: Buffer.from(sections) })
