import { randomUUID } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'

test('selects, traces, reviews, exports and revokes synthetic content', async ({ page }) => {
  await page.goto('/')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Email')).toBeFocused()
  await page.getByRole('button', { name: 'Create an account' }).click()
  await page.getByLabel('Email').fill(`browser-workflow-${randomUUID()}@example.test`)
  await page.getByLabel('Password').fill('synthetic-browser-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Timeline' })).toBeVisible()

  const file = page.locator('.file-drop input')
  await file.setInputFiles({ name: 'unknown.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.getByRole('alert')).toBeVisible()
  await file.setInputFiles('../fixtures/synthetic/conversations.json')
  await page.getByRole('checkbox', { name: /Choose a portable notes format/ }).check()
  await page.getByRole('button', { name: 'Import selected' }).click()
  const decision = page.getByText('Keep structured records in Postgres and make approved notes portable as Markdown.', { exact: true })
  await expect(decision).toBeVisible()
  await expect(page.locator('.timeline-item')).toHaveCount(2)

  const sections = Array.from({ length: 101 }, (_, index) => '## 2026-11-20 Synthetic section ' + index + '\n\nGenerated pagination material.').join('\n\n')
  await file.setInputFiles({ name: 'pagination.md', mimeType: 'text/markdown', buffer: Buffer.from(sections) })
  await page.getByRole('button', { name: 'Import selected' }).click()
  await expect(page.locator('.timeline-item')).toHaveCount(100)
  await page.getByRole('button', { name: 'Load more timeline items' }).click()
  await expect(page.locator('.timeline-item')).toHaveCount(103)
  await expect(decision).toBeVisible()

  const reviewNav = page.getByRole('button', { name: /Weekly review/ })
  await reviewNav.focus()
  await expect(reviewNav).toBeFocused()
  await page.keyboard.press('Enter')
  await page.locator('input[name=start]').fill('2026-11-16')
  await page.locator('input[name=end]').fill('2026-11-19')
  await page.getByRole('button', { name: 'Generate draft' }).click()
  await page.getByText(/^Evidence \(\d+\)$/).click()
  await page.getByRole('button', { name: /Open source in timeline/ }).last().click()
  await expect(decision).toBeVisible()
  await reviewNav.click()
  const editor = page.getByPlaceholder(/Edit your review/)
  await editor.fill('A verified synthetic reflection.')
  await page.getByRole('button', { name: 'Confirm & save' }).click()
  await expect(page.getByText('CONFIRMED', { exact: true })).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export Markdown' }).click()
  expect(await readFile(await (await download).path(), 'utf8')).toContain('A verified synthetic reflection.')

  await page.getByPlaceholder('What should you follow up on?').fill('Synthetic follow-up')
  await page.getByRole('button', { name: 'Add reminder' }).click()
  await page.getByRole('button', { name: 'Snooze' }).click()
  await expect(page.getByText(/· snoozed/)).toBeVisible()
  await page.getByRole('button', { name: 'Dismiss' }).click()
  await expect(page.getByText(/· cancelled/)).toBeVisible()

  await page.getByPlaceholder('What should you follow up on?').fill('Overdue synthetic follow-up')
  await page.getByLabel('Reminder due date').fill('2020-01-01T10:00')
  await page.getByRole('button', { name: 'Add reminder' }).click()
  await expect(page.locator('.nav-badge')).toHaveText('1')
  const duePanel = page.locator('.due-reminders')
  await expect(duePanel.getByText('Overdue synthetic follow-up')).toBeVisible()
  await duePanel.getByRole('button', { name: 'Complete' }).click()
  await expect(page.locator('.nav-badge')).toHaveCount(0)

  const schedulePanel = page.locator('.schedule-panel')
  await schedulePanel.getByRole('checkbox', { name: 'Enable automatic weekly review' }).check()
  await schedulePanel.getByLabel('Day').selectOption('6')
  await schedulePanel.getByLabel('Time').fill('20:00')
  await schedulePanel.getByRole('button', { name: 'Save schedule' }).click()
  await expect(page.getByText('Weekly review schedule saved.')).toBeVisible()
  await expect(schedulePanel.getByText(/^Next /)).toBeVisible()

  const nav = page.getByRole('navigation', { name: 'Main navigation' })
  const searchNav = nav.getByRole('button', { name: /Search/ })
  const searchInput = page.getByLabel('Search timeline, reviews, and reminders')
  const searchGroup = (name: RegExp) => page.locator('.search-group').filter({ has: page.getByRole('heading', { name }) })

  await searchNav.focus()
  await expect(searchNav).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Search', exact: true })).toBeVisible()

  await searchInput.fill('A verified synthetic reflection.')
  await searchInput.press('Enter')
  const reviewsGroup = searchGroup(/^Weekly reviews/)
  await expect(reviewsGroup).toBeVisible()
  await expect(reviewsGroup.getByText('A verified synthetic reflection.', { exact: true })).toBeVisible()
  const reviewResult = reviewsGroup.getByRole('button').first()
  await expect(reviewResult).toBeVisible()
  await reviewResult.focus()
  await expect(reviewResult).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Weekly review', exact: true })).toBeVisible()
  await expect(page.getByText('CONFIRMED', { exact: true })).toBeVisible()

  await searchNav.click()
  await searchInput.fill('Synthetic follow-up')
  await searchInput.press('Enter')
  const remindersGroup = searchGroup(/^Reminders/)
  await expect(remindersGroup).toBeVisible()
  await expect(remindersGroup).toContainText('Synthetic follow-up')
  await remindersGroup.getByRole('button').first().click()
  await expect(page.getByRole('heading', { name: 'Weekly review', exact: true })).toBeVisible()
  await expect(page.getByText('Synthetic follow-up', { exact: true })).toBeVisible()

  await searchNav.click()
  const decisionQuery = 'Keep structured records in Postgres and make approved notes portable as Markdown.'
  await searchInput.fill(decisionQuery)
  await searchInput.press('Enter')
  const timelineGroup = searchGroup(/^Timeline/)
  await expect(timelineGroup).toBeVisible()
  const timelineResult = timelineGroup.getByRole('button').first()
  await expect(timelineResult).toBeVisible()
  await timelineResult.focus()
  await expect(timelineResult).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Timeline', exact: true })).toBeVisible()
  await expect(page.getByText(decisionQuery, { exact: true })).toBeVisible()

  await searchNav.click()
  await searchInput.fill('NoSuchSyntheticTerm')
  await searchInput.press('Enter')
  await expect(page.getByText('No results', { exact: true })).toBeVisible()

  const failedQuery = 'Synthetic follow-up'
  await page.route('**/api/v1/search?**', (route) => route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: { message: 'Synthetic search failure.' } }) }))
  await searchInput.fill(failedQuery)
  await searchInput.press('Enter')
  await expect(page.getByRole('alert')).toContainText('Synthetic search failure.')
  await expect(searchInput).toHaveValue(failedQuery)
  await page.unroute('**/api/v1/search?**')

  await page.getByRole('button', { name: /Account & sources/ }).click()
  const chat = page.locator('.manage-source').filter({ hasText: 'conversations.json' })
  await chat.getByRole('button', { name: 'Revoke' }).click()
  await expect(chat.getByText(/· revoked/)).toBeVisible()

  let deleteMessage = ''
  page.once('dialog', async (dialog) => {
    deleteMessage = dialog.message()
    await dialog.dismiss()
  })
  await page.getByRole('button', { name: /Timeline/ }).click()
  await expect(page.locator('.timeline-item').first()).toBeVisible()
  await page.locator('.timeline-item').first().getByRole('button', { name: 'Delete imported source' }).click()
  expect(deleteMessage).toContain('every timeline entry created from that source')
})

test('enforces photo directory limits and reports partial imports', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Create an account' }).click()
  await page.getByLabel('Email').fill(`browser-photos-${randomUUID()}@example.test`)
  await page.getByLabel('Password').fill('synthetic-browser-password')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Timeline' })).toBeVisible()

  const folder = testInfo.outputPath('photo-input')
  const oversized = testInfo.outputPath('oversized-directory')
  await mkdir(folder, { recursive: true })
  await mkdir(oversized, { recursive: true })
  const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/lZkAAAAASUVORK5CYII=', 'base64')
  await writeFile(join(folder, 'valid.png'), png)
  await writeFile(join(folder, 'invalid.png'), 'Synthetic invalid photo')
  await writeFile(join(folder, 'ignored.txt'), 'Synthetic non-photo')
  await Promise.all(Array.from({ length: 11 }, (_, index) => writeFile(join(oversized, index + '.png'), png)))
  const input = page.locator('.folder-picker input')
  const submit = page.getByRole('button', { name: 'Import selected' })
  await input.setInputFiles(folder)
  await expect(submit).toBeEnabled()
  await input.setInputFiles(oversized)
  await expect(page.getByRole('alert')).toContainText('Select at most 10 photos')
  await expect(submit).toBeDisabled()
  await input.setInputFiles(folder)
  await expect(page.getByRole('status')).toContainText('1 non-photo file(s)')
  await submit.click()
  await expect(page.getByRole('alert')).toContainText('1 photo(s) could not be imported: invalid.png')
  await expect(page.locator('.timeline-item')).toHaveCount(1)
})
